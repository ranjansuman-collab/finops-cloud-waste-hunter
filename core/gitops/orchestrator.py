"""
core/gitops/orchestrator.py
Coordinates end-to-end GitOps workflow with strict safety boundaries.

Workflow:
1. Validates Git & GitHub provider availability.
2. Creates isolated branch: finops/<resource>/<action>.
3. Verifies file safety and stages only valid Terraform files.
4. Commits change with descriptive FinOps message.
5. Pushes to remote repository.
6. Opens GitHub Pull Request with complete FinOps audit trail.

Safety Invariants:
- PR creation NEVER executes terraform apply automatically.
- Merging PR is NEVER automated.
- Simulation mode is preserved and isolated.
- Live mode NEVER fakes Git or GitHub success.

ISWE309L Cloud Computing - Course Project Review-1
Team: Vivek Pandey (24MIS0216) & S. Hemal (24MIS0050)
"""

