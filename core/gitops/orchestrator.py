def build_pr_body(
    findings: List[WasteFinding],
    costs: Optional[List[CostFinding]],
    recommendations: Optional[List[AIRecommendation]],
    total_savings: float,
    patches: Optional[List[TerraformPatch]] = None,
    is_destructive: bool = False,
) -> str:
    """Builds comprehensive FinOps Pull Request markdown documentation."""
    cost_map = {c.finding_id: c for c in (costs or [])}
    rec_map = {r.finding_id: r for r in (recommendations or [])}

    lines = [
        "## 🚀 FinOps Automated Remediation Proposal",
        "",
        "> [!IMPORTANT]",
        "> **This change has NOT been automatically applied to AWS.**",
        "> Merging this PR triggers code review only. Terraform apply requires separate, explicit human approval.",
        "",
        f"### 💰 Projected Monthly Savings: `${total_savings:.2f} / month`",
        f"- **Destructive Operation Flag:** `{'YES — High Risk / Deletion' if is_destructive else 'No — Non-destructive / Right-sizing'}`",
        "- **Workflow Gate:** Engineering peer review required.",
        "",
        "### 🔍 Detected Waste Resources & Remediation Actions",
        "| Resource | Type | Category | Monthly Savings | Recommended Action |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]

    for f in findings:
        c = cost_map.get(f.id)
        savings_text = f"${c.monthly_savings:.2f}" if c else "$0.00"
        lines.append(f"| `{f.resource_name}` | {f.resource_type} | `{f.waste_category}` | **{savings_text}** | `{f.recommended_specs}` |")

    lines.extend([
        "",
        "### 🤖 AI Bedrock Advisor Rationale",
    ])
    for f in findings:
        r = rec_map.get(f.id)
        if r:
            lines.append(f"- **{f.resource_name} ({r.risk_level}):** {r.rationale}")
        else:
            lines.append(f"- **{f.resource_name}:** Automated optimization recommended.")

    lines.extend([
        "",
        "### 🛡️ Safety & Quality Verification",
        "- [x] `terraform fmt -check`: Syntax formatting verified",
        "- [x] `terraform validate`: Configuration syntax validated",
        "- [x] Credential Check: No secrets, passwords, or AWS keys included in diff",
        "- [ ] Human Approval: Awaiting engineering sign-off",
        "",
        "---",
        "*Automated PR generated by FinOps Cloud Waste Hunter (VIT ISWE309L)*",
    ])

    return "\n".join(lines)


class GitOpsOrchestrator:
    """Coordinates local Git branching and remote GitHub PR creation."""

    def __init__(
        self,
        repo_dir: Optional[Path] = None,
        use_live_gitops: bool = False,
    ):
        self.repo_dir = repo_dir
        self.use_live_gitops = use_live_gitops
        self.git = GitService(repo_dir=repo_dir)
        self.github = GitHubProvider()

    def create_remediation_pr(
        self,
        run_id: str,
        findings: List[WasteFinding],
        costs: Optional[List[CostFinding]] = None,
        recommendations: Optional[List[AIRecommendation]] = None,
        patches: Optional[List[TerraformPatch]] = None,
        total_monthly_savings: float = 0.0,
        files_to_commit: Optional[List[str]] = None,
        is_destructive: bool = False,
        base_branch: str = "main",
    ) -> GitOpsWorkflowResult:
        """
        Executes GitOps PR pipeline.
        In simulation mode: creates simulated in-memory PR.
        In live mode: executes real Git branching, commit, push, and GitHub PR creation.
        NEVER executes terraform apply.
        """
        if not findings:
            return GitOpsWorkflowResult(
                status=STATUS_SUCCESS,
                mode="LIVE" if self.use_live_gitops else "SIMULATION",
                message="No waste findings provided; no GitOps PR required.",
            )

        # -------------------------------------------------------------
        # 1. Simulation Mode
        # -------------------------------------------------------------
        if not self.use_live_gitops:
            from core.module7_gitops import GitOpsReviewModule
            sim_module = GitOpsReviewModule()
            sim_pr = sim_module.create_pull_request(
                run_id=run_id,
                patches=patches or [],
                findings=findings,
                costs=costs or [],
                recommendations=recommendations or [],
                total_monthly_savings=total_monthly_savings,
                total_annualized_savings=total_monthly_savings * 12,
            )
            return GitOpsWorkflowResult(
                status=STATUS_SUCCESS,
                mode="SIMULATION",
                branch=sim_pr.branch_name,
                commit_hash=f"sim-{run_id[-7:]}",
                pr_number=sim_pr.pr_number,
                pr_url=f"https://github.com/example/repo/pull/{sim_pr.pr_number}",
                is_destructive=is_destructive,
                files_changed=sim_pr.files_changed,
                requires_human_approval=True,
                automatic_apply_triggered=False,
                message=f"Simulated GitOps PR #{sim_pr.pr_number} generated successfully.",
            )

        # -------------------------------------------------------------
        # 2. Live Mode Pre-flight Checks
        # -------------------------------------------------------------
        # Check Git CLI
        git_avail, git_msg = self.git.is_git_available()
        if not git_avail:
            return GitOpsWorkflowResult(
                status=STATUS_GIT_NOT_INSTALLED,
                mode="LIVE",
                message=f"Git is not installed or available: {git_msg}",
                errors=[git_msg],
            )

        # Check repository
        is_repo, repo_msg = self.git.is_repo()
        if not is_repo:
            return GitOpsWorkflowResult(
                status=STATUS_GIT_REPOSITORY_NOT_FOUND,
                mode="LIVE",
                message=f"Current directory is not a Git repository: {repo_msg}",
                errors=[repo_msg],
            )

        # Check GitHub configuration
        gh_conf, gh_msg = self.github.is_configured()
        if not gh_conf:
            return GitOpsWorkflowResult(
                status=gh_msg,
                mode="LIVE",
                message=f"GitHub provider is not configured: {gh_msg}",
                errors=[gh_msg],
            )

        # -------------------------------------------------------------
        # 3. Live Branch Creation
        # -------------------------------------------------------------
        primary_resource = findings[0].resource_name if findings else "infra"
        primary_action = "downsize" if findings[0].waste_category.value == "OVERSIZED_COMPUTE" else "optimize"
        branch_name = sanitize_branch_name(primary_resource, primary_action)

        branch_res = self.git.create_and_checkout_branch(branch_name, base_branch=base_branch)
        if branch_res.status not in (STATUS_SUCCESS, "BRANCH_EXISTS"):
            return GitOpsWorkflowResult(
                status=branch_res.status,
                mode="LIVE",
                branch=branch_name,
                message=f"Branch creation failed: {branch_res.message}",
                errors=[branch_res.message],
            )

        # -------------------------------------------------------------
        # 4. Stage Verified Files Only
        # -------------------------------------------------------------
        target_files = files_to_commit or ["sample_infrastructure/main.tf"]
        stage_res = self.git.stage_files(target_files)
        if not stage_res.success:
            return GitOpsWorkflowResult(
                status=stage_res.status,
                mode="LIVE",
                branch=branch_name,
                message=f"File staging failed: {stage_res.stderr}",
                errors=[stage_res.stderr],
            )

        # -------------------------------------------------------------
        # 5. Commit
        # -------------------------------------------------------------
        commit_msg = f"FinOps: optimize {len(findings)} resource(s) - save ${total_monthly_savings:.2f}/mo"
        commit_res = self.git.commit(commit_msg)
        if commit_res.status == STATUS_FILE_SECURITY_VIOLATION:
            return GitOpsWorkflowResult(
                status=STATUS_FILE_SECURITY_VIOLATION,
                mode="LIVE",
                branch=branch_name,
                message=commit_res.details,
                errors=[commit_res.details],
            )

        # -------------------------------------------------------------
        # 6. Push Branch
        # -------------------------------------------------------------
        push_res = self.git.push(branch_name, remote="origin")
        if not push_res.pushed:
            return GitOpsWorkflowResult(
                status=push_res.status,
                mode="LIVE",
                branch=branch_name,
                commit_hash=commit_res.commit_hash,
                message=f"Push failed: {push_res.message}",
                errors=[push_res.message],
            )

        # -------------------------------------------------------------
        # 7. Create GitHub PR
        # -------------------------------------------------------------
        pr_title = f"FinOps: Optimize {primary_resource} [Save ${total_monthly_savings:.2f}/mo]"
        pr_body = build_pr_body(
            findings=findings,
            costs=costs,
            recommendations=recommendations,
            total_savings=total_monthly_savings,
            patches=patches,
            is_destructive=is_destructive,
        )

        pr_res = self.github.create_pull_request(
            title=pr_title,
            body=pr_body,
            head_branch=branch_name,
            base_branch=base_branch,
        )

        if pr_res.status != STATUS_SUCCESS:
            return GitOpsWorkflowResult(
                status=pr_res.status,
                mode="LIVE",
                branch=branch_name,
                commit_hash=commit_res.commit_hash,
                message=f"Pull Request creation failed: {pr_res.message}",
                errors=[pr_res.message],
            )

        return GitOpsWorkflowResult(
            status=STATUS_SUCCESS,
            mode="LIVE",
            branch=branch_name,
            commit_hash=commit_res.commit_hash,
            pr_number=pr_res.pr_number,
            pr_url=pr_res.pr_url,
            is_destructive=is_destructive,
            files_changed=target_files,
            requires_human_approval=True,
            automatic_apply_triggered=False,
            message=f"Live Pull Request #{pr_res.pr_number} created on {self.github.repository}.",
        )
